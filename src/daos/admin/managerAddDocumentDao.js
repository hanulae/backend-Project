/**
 * 상조팀장 추가 문서 관리 DAO (Data Access Object)
 * - 관리자가 상조팀장이 업로드한 추가 문서들을 관리하는 데이터베이스 작업을 담당합니다.
 * - 문서 업로드, 상조팀장별 문서 조회, 문서 이력 관리 등의 기능을 제공합니다.
 * - Sequelize ORM을 사용하여 데이터베이스와의 상호작용을 처리합니다.
 * - 트랜잭션 지원을 통해 문서 업로드 과정의 데이터 일관성을 보장합니다.
 * - 상조팀장별로 문서를 체계적으로 관리할 수 있어 사용자 그룹별 문서 현황 파악이 가능합니다.
 * - 이모지(📄)를 사용하여 로그 메시지를 시각적으로 구분하여 디버깅을 용이하게 합니다.
 * - 장례식장 추가 문서 관리와 유사한 구조로 일관된 문서 관리 시스템을 제공합니다.
 */
import db from '../../models/index.js';

/**
 * 새로운 상조팀장 추가 문서 생성
 *
 * 입력:
 * - data: Object — 생성할 문서 정보 객체
 * - options: Object — Sequelize 옵션 (기본값: {})
 *
 * 동작:
 * 1) 입력받은 문서 정보로 새로운 ManagerAddDocument 레코드 생성
 * 2) 트랜잭션 옵션을 포함하여 데이터베이스에 문서 정보 저장
 * 3) 오류 발생 시 상세한 로그와 함께 원본 오류 전파
 *
 * 생성 정보:
 * - 문서 기본 정보 (파일명, 경로, 타입 등)
 * - 상조팀장 ID, 업로드 시간 등 메타데이터
 * - 자동 생성: 문서 ID, createdAt, updatedAt
 *
 * 트랜잭션 지원:
 * - options 파라미터를 통해 트랜잭션 전달 가능
 * - 문서 업로드와 관련된 다른 작업들과 함께 원자적 처리
 * - 데이터 일관성 보장을 위한 롤백 지원
 *
 * 반환:
 * - Object: 생성된 문서 정보
 *
 * 예외:
 * - DB 생성 실패: 원본 오류를 그대로 전파
 * - DB 연결 오류: Sequelize에서 발생한 데이터베이스 오류 전파
 * - 로그: '📄 문서 업로드 DAO 오류: {오류메시지}' 형태로 콘솔 출력
 *

 *
 * 참고:
 * - 이 함수는 상조팀장이 추가 문서를 업로드할 때 사용됩니다.
 * - 트랜잭션을 통해 문서 업로드와 관련된 다른 작업들을 함께 처리할 수 있습니다.
 * - 파일 업로드와 함께 문서 메타데이터를 데이터베이스에 저장합니다.
 * - 이모지 로그를 통해 문서 관련 오류를 시각적으로 구분할 수 있습니다.
 * - 문서 타입, 파일 크기, MIME 타입 등 상세한 문서 정보를 관리할 수 있습니다.
 * - 업로드된 문서는 상조팀장 ID와 연결되어 체계적으로 관리됩니다.
 * - 장례식장 추가 문서 관리와 유사한 구조로 일관된 사용자 경험을 제공합니다.
 * - 상조팀장의 사업자등록증, 자격증, 보험증 등 필수 서류 관리에 활용됩니다.
 * - 문서 검증과 승인 과정에서 상조팀장의 자격과 신뢰성을 확인하는 데 사용됩니다.
 */
export const create = async (data, options = {}) => {
  try {
    return await db.ManagerAddDocument.create(data, options); // 트랜잭션 포함
  } catch (error) {
    console.error('📄 문서 업로드 DAO 오류:', error.message);
    throw error;
  }
};
