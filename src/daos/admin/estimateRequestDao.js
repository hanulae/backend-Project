/**
 * 견적 신청 관리 DAO (Data Access Object)
 * - 관리자가 상조팀장과 장례식장의 견적 신청 내역을 조회하고 관리하는 데이터베이스 작업을 담당합니다.
 * - 사용자별 견적 신청 현황 파악, 견적 처리 상태 모니터링, 견적 이력 추적 등의 기능을 제공합니다.
 * - Sequelize ORM을 사용하여 데이터베이스와의 상호작용을 처리합니다.
 * - 견적 신청 데이터를 시간순으로 정렬하여 최신 견적 신청부터 확인할 수 있도록 설계되었습니다.
 * - 상조팀장과 장례식장의 견적 신청을 구분하여 관리할 수 있어 사용자 그룹별 견적 현황 파악이 가능합니다.
 */
import db from '../../models/index.js';

/**
 * 특정 상조팀장의 견적 신청 내역 조회
 *
 * 입력:
 * - managerId: string — 조회할 상조팀장의 고유 ID
 *
 * 동작:
 * 1) managerId로 해당 상조팀장이 신청한 모든 견적 요청 조회
 * 2) 생성일 기준 내림차순 정렬 (최신 견적 신청 순)
 * 3) 오류 발생 시 상세한 오류 메시지와 함께 Error throw
 *
 * 조회 조건:
 * - managerId와 일치하는 견적 신청 레코드들
 * - findAll을 사용하여 모든 관련 견적 신청 조회
 *
 * 정렬:
 * - createdAt DESC (최신 견적 신청 순)
 *
 * 반환:
 * - Array<Object>: 해당 상조팀장의 견적 신청 내역 배열
 *
 * 예외:
 * - DB 조회 실패: '상조팀장 견적 신청 내역 조회 오류: {오류메시지}' 형태로 Error throw
 * - DB 연결 오류: Sequelize에서 발생한 데이터베이스 오류 전파
 *

 *
 * 참고:
 * - 이 함수는 관리자가 특정 상조팀장의 견적 신청 현황을 파악할 때 사용됩니다.
 * - 최신 견적 신청부터 표시되어 최근 활동을 우선적으로 확인할 수 있습니다.
 * - 반환값이 빈 배열인 경우 해당 상조팀장이 견적을 신청한 내역이 없음을 의미합니다.
 * - 견적 신청 상태, 요청 금액, 대상 장례식장 등 상세한 견적 정보를 확인할 수 있습니다.
 * - 상조팀장별 견적 활동 분석이나 업무 성과 평가에 활용할 수 있습니다.
 * - 대량의 견적 신청이 있을 경우 페이지네이션이나 필터링 기능을 고려해야 할 수 있습니다.
 */
export const findEstimateRequestsByManagerId = async (managerId) => {
  try {
    return await db.EstimateRequest.findAll({
      where: { managerId },
      order: [['createdAt', 'DESC']],
    });
  } catch (error) {
    throw new Error('상조팀장 견적 신청 내역 조회 오류: ' + error.message);
  }
};

